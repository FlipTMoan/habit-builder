function isActive(tab: Route, current: Route): boolean {
  if (tab.name === current.name) return true
  if (tab.name === 'dashboard' && current.name === 'habit') return true
  return false
}

export default function NavBar({ route }: { route: Route }) {
  return (
    <nav className="navbar" aria-label="Primary">
      <div className="navbar-inner">
        {TABS.map((t) => (
          <button
            key={t.label}
            className={`nav-item ${isActive(t.route, route) ? 'active' : ''}`}
            onClick={() => navigate(t.route)}
          >
            {t.icon}
            <span>{t.label}</span>
          </button>
        ))}
      </div>
    </nav>
  )
}